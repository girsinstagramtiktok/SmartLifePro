'use strict';
const fs=require('fs'),vm=require('vm'),assert=require('assert');
const core=require('./smarty-money-core.js');
const store={settings:{currency:'R$',lang:'es'},smartyMoney:{accounts:[],cards:[],incomes:[],savings:[],movements:[],fixedSources:{},preferences:{}}};
const st=core.state(store);
const nu=core.createAccount(st,{name:'Nubank principal',bankDomain:'',openingBalance:250});
const bb=core.createAccount(st,{name:'Banco do Brasil',bankDomain:'bb.com.br',openingBalance:500});
const card=core.createCard(st,{name:'Cartão Nu',bankDomain:'nubank.com.br',limit:1500,cutoffDay:20,dueDay:5});
core.createMovement(st,{kind:'expense',accountId:nu.id,amount:12,date:core.today(),note:'Mercado'});
const homeEl={innerHTML:'',querySelectorAll:()=>[]}, titleEl={textContent:''}, seeAllEl={textContent:''};
const elements={'bento-wallet-items':homeEl,'bento-wallet-title':titleEl,'bento-wallet-see-all':seeAllEl};
const document={readyState:'loading',addEventListener:()=>{},getElementById:id=>elements[id]||null};
const window={addEventListener:()=>{},SmartyMoneyCore:core};
const sandbox={window,document,Data:{store},queueMicrotask,console};
vm.runInNewContext(fs.readFileSync('./smarty-wallet.js','utf8'),sandbox);
const wallet=window.SmartyWallet;
assert(wallet);
assert.equal(wallet.brand(nu).id,'nubank','detect Nubank from name when domain missing');
assert.equal(wallet.brand(bb).id,'bb');
assert.equal(wallet.brand(card).id,'nubank');
wallet.renderHome();
assert(homeEl.innerHTML.includes('Nubank principal'));
assert(homeEl.innerHTML.includes('Banco do Brasil'));
assert(homeEl.innerHTML.includes('Cartão Nu'));
assert(!homeEl.innerHTML.includes('250,00'),'home must never expose account balance');
assert(!homeEl.innerHTML.includes('1.500,00'),'home must never expose credit limit');
assert(wallet.financeCards(st,'account').includes('R$ 238,00'));
assert(wallet.financeCards(st,'card').includes('R$ 1.500,00'));
const advice=wallet.advisorContext('¿Cuánto tengo disponible en Nubank y mi tarjeta?');
assert(advice.includes('Nubank principal'));
assert(advice.includes('238,00'));
assert(advice.includes('1.500,00'));
assert(!wallet.advisorContext('¿Qué hora es?'));
console.log('OK: branded wallet, home without balances, detail values, Smarty context');
