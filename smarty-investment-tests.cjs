'use strict';
const assert=require('node:assert/strict');
const C=require('./smarty-money-core.js');
const Cat=require('./smarty-investment-catalog.js');
const st=C.state({});
const account=C.createAccount(st,{name:'Nubank',bankDomain:'nubank.com.br',openingBalance:1000});
const card=C.createCard(st,{name:'Cartão Nu',limit:5000,openingUsed:1000,cutoffDay:20,dueDay:5});
const m=C.createMovement(st,{kind:'card-charge',cardId:card.id,amount:200,date:'2026-11-02'});
const key=card.id;
C.updateCard(st,card.id,{name:'Crédito principal',limit:3500,openingUsed:1100,cutoffDay:21,dueDay:8,noticeDays:4,payAccountId:account.id});
assert.equal(card.id,key);assert.equal(st.movements.length,1,'No eliminar historial');
assert.equal(C.cardAvailable(st,card.id),220000,'Límite editado y deuda recalculada');
assert.equal(card.cutoffDay,21);assert.equal(card.dueDay,8);
const balance=C.accountBalance(st,account.id);
C.updateAccount(st,account.id,{name:'Mi banco',bankDomain:'bb.com.br',type:'wallet'});
assert.equal(C.accountBalance(st,account.id),balance);assert.equal(account.bankDomain,'bb.com.br');
assert.throws(()=>C.updateCard(st,card.id,{limit:-1}),/importe|inválido/i);assert.equal(card.limitCents,350000);
const inc=C.createIncome(st,{name:'Pago',amount:3000,accountId:account.id});
C.updateIncome(st,inc.id,{name:'Salario',amount:3200,rule:'upto_business',businessDay:5});
assert.equal(inc.amountCents,320000);assert.equal(inc.id,st.incomes[0].id);
const by=id=>{const p=Cat.byId(id);assert(p);return p};
assert.equal(by('nubank-caixinha').cdiPercent,100);
assert.equal(by('nubank-turbo-115').cdiPercent,115);
assert.equal(by('bb-rende-facil').cdiPercent,null,'No suponer rendimiento del BB Rende Fácil');
assert.equal(by('poupanca').rateType,'poupanca');
assert.equal(by('inter-dia').cdiPercent,null,'hasta 80% no es 80% garantizado');
assert.equal(by('99-cofrinho').excessPercent,80);
const rates=Cat.marketRates(st.preferences);assert(rates.cdiAnnual>0);
let opt=Cat.defaultFor('nubank-caixinha',rates);
const saving=C.createSaving(st,{name:'Caixinha Nu',principal:1000,referenceDate:'2026-01-01',autoMarket:true,...opt});
assert.equal(saving.cdiPercent,100);assert.equal(saving.cdiAnnual,rates.cdiAnnual);
const sid=saving.id;
let proj=C.savingsProjection(saving,'2027-01-01');
assert(proj.interestCents>0,'Caixinha debe rendir');
const interestBefore=proj.interestCents;
C.updateSaving(st,sid,{name:'Ahorro editado',cdiPercent:115});
assert.equal(sid,saving.id);assert(C.savingsProjection(saving,'2027-01-01').interestCents>interestBefore);
assert.equal(st.savings.length,1);
C.savingDeposit(st,saving.id,account.id,100,'2026-11-13');
const entries=saving.entries.length;
C.updateSaving(st,saving.id,{name:'Ahorro con deposito'});
assert.equal(saving.entries.length,entries,'Editar conserva depósitos');
C.applyMarketRates(st,{cdiAnnual:10,selicAnnual:10,trMonthly:0.2,asOf:'2026-11-13'});
assert.equal(saving.cdiAnnual,10);
const pending=C.createSaving(st,{name:'BB Rende Fácil',principal:500,referenceDate:'2026-01-01',...Cat.defaultFor('bb-rende-facil',rates)});
assert.equal(pending.cdiPercent,0);assert.equal(C.savingsProjection(pending,'2026-11-13').needsRate,true);
const fixed=C.createSaving(st,{name:'CDB',principal:1000,rateType:'annual',annualRate:12,referenceDate:'2026-01-01'});
assert(Math.abs(C.savingsProjection(fixed,'2027-01-01').grossCents-112000)<60);
const pou=C.createSaving(st,{name:'Poupança',principal:1000,referenceDate:'2026-01-10',...Cat.defaultFor('poupanca',rates)});
assert.equal(C.savingsProjection(pou,'2026-02-09').interestCents,0,'No cobrar intereses antes del aniversario');
const f=C.savingsProjection(pou,'2026-02-10');assert(f.interestCents>0);
assert.equal(C.savingsProjection(pou,'2026-03-09').interestCents,f.interestCents,'No abonar antes de otro aniversario');
assert(C.savingsProjection(pou,'2026-03-10').interestCents>f.interestCents);
const same=C.createSaving(st,{name:'Hoy',principal:100,referenceDate:'2026-11-13',rateType:'annual',annualRate:10});
C.savingDeposit(st,same.id,account.id,25,'2026-11-13');
assert.equal(C.savingsProjection(same,'2026-11-13').grossCents,12500,'Depósitos del mismo día aparecen');
