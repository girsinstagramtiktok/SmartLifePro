'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const src = fs.readFileSync(path.join(__dirname,'smarty-ota.js'),'utf8');
new vm.Script(src,{filename:'smarty-ota.js'});
assert.match(src,/SMARTY_PATCH_BUILD_ID\s*=\s*'smarty-light-/);
assert.match(src,/smarty-prepaint/,'El parche debe liberar la vista después del montaje');
assert.match(src,/fin-hero-donut/);
assert.match(src,/fin-smarty-dock/);
assert.match(src,/smarty-theme-sheet/);
const workflow = fs.readFileSync(path.join(__dirname,'.github/workflows/android-apk.yml'),'utf8');
assert.match(workflow,/cp smarty-ota\.js www\/smarty-ota\.js/);
assert.match(workflow,/smarty-prepaint/);
assert.match(workflow,/main\.js/);
assert.doesNotMatch(workflow,/releases\/download/);
console.log('OK: el parche actual se incluye localmente y el arranque no espera al script remoto.');
